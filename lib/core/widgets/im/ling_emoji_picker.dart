  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final emojis = _emojiSets[_currentIndex];

    return Container(
      height: widget.height,
      color: widget.backgroundColor ?? theme.colorScheme.surface,
      child: Column(
        children: [
          // Category tabs
